def oui_from_mac(mac: str | None) -> str | None:
    """从规范化或原始 MAC 提取 6 位 OUI 十六进制；无效则 ``None``。"""
    if not mac or mac.strip() in ("", "—"):
        return None
    norm = normalize_mac(mac)
    parts = norm.split("-")
    if len(parts) < 3:
        return None
    return (parts[0] + parts[1] + parts[2]).upper()


def lookup_vendor(mac: str | None) -> str:
    """查厂商名；无 MAC 或未命中返回 ``—``。"""
    oui = oui_from_mac(mac)
    if not oui:
        return "—"
    return _OUI_SHORT.get(oui, "—")
